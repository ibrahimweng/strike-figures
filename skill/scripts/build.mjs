function resolvesIn(ref, c, names) {
  if (ref.includes('*')) {
    const re = new RegExp('^' + basename(ref).replace(/[.]/g, '\\.').replace(/\*/g, '.*') + '$');
    return [...names].some((n) => re.test(n));
  }
  if (ref.includes('/')) return existsSync(join(c.base, ref));
  if (/\.(svg|png)$/.test(ref)) return existsSync(join(c.logos, ref));
  return names.has(ref);
}

