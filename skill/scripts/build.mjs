// ---------------------------------------------------------------- the build

export async function build(opts) {
  const { out, source, assets } = opts;
  if (out === ROOT || ROOT.startsWith(out + sep) || [source, assets, opts.scripts].some((p) => p === out || p.startsWith(out + sep))) {
    throw new Error(`Refusing to write to ${out}: it holds the sources.`);
  }
  // Only ever empty a folder that holds an earlier build (or nothing).
  const ours = new Set([...TARGETS, 'tokens', 'STRIKE-DESIGN.md', 'core.md', 'llms.txt', 'manifest.json']);
  if (existsSync(out) && !opts.force && readdirSync(out).some((n) => !ours.has(n))) {
    throw new Error(`Refusing to empty ${out}: it holds files this build didn't make. Pass --force to replace it.`);
  }
  const notes = [];
  let pngs = [];
  const tmp = mkdtempSync(join(tmpdir(), 'strike-build-'));
  try {
    const logoSvgs = listFiles(join(assets, 'logo')).filter((f) => f.endsWith('.svg'));
    if (opts.png) {
      mkdirSync(join(tmp, 'png'));
      const r = await renderPngs(logoSvgs, join(tmp, 'png'));
      if (r.ok) pngs = r.files;
      else notes.push(`PNG renders skipped: ${r.reason}.`);
    } else notes.push('PNG renders skipped (--no-png).');
    let result = buildOnce(opts, pngs, tmp);
    if (result.total > SIZE_BUDGET && pngs.length) {
      result = buildOnce(opts, [], tmp);
      notes.push(`PNG renders skipped: with them the output passed ${kb(SIZE_BUDGET)}.`);
    }
    result.notes.unshift(...notes);
    if (result.total > SIZE_BUDGET) result.notes.push(`The output is ${kb(result.total)}, over the ${kb(SIZE_BUDGET)} budget.`);
    return result;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

