const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  if (typeof zlib.crc32 === 'function') return zlib.crc32(buf) >>> 0;
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

// entries: [{ name: 'a/b.txt', data: Buffer }]. Folder entries are added.
export function makeZip(entries) {
  const DOS_DATE = ((2026 - 1980) << 9) | (1 << 5) | 1; // fixed, so builds are reproducible
  const all = [];
  const dirs = new Set();
  for (const e of entries) {
    const parts = e.name.split('/');
    for (let i = 1; i < parts.length; i++) dirs.add(parts.slice(0, i).join('/') + '/');
  }
  for (const d of [...dirs].sort()) all.push({ name: d, data: Buffer.alloc(0), dir: true });
  for (const e of [...entries].sort((a, b) => (a.name < b.name ? -1 : 1))) all.push(e);

  const parts = [];
  const centrals = [];
  let offset = 0;
  for (const e of all) {
    const name = Buffer.from(e.name, 'utf8');
    const raw = e.data;
    const deflated = e.dir ? raw : zlib.deflateRawSync(raw, { level: 9 });
    const deflate = !e.dir && deflated.length < raw.length;
    const body = deflate ? deflated : raw;
    const crc = crc32(raw);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(deflate ? 8 : 0, 8);
    local.writeUInt16LE(0, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(body.length, 18);
    local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    parts.push(local, name, body);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE((3 << 8) | 20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(deflate ? 8 : 0, 10);
    central.writeUInt16LE(0, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(body.length, 20);
    central.writeUInt32LE(raw.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(0, 30);
    central.writeUInt32LE(0, 34);
    central.writeUInt32LE((((e.dir ? 0o40755 : 0o100644) << 16) | (e.dir ? 0x10 : 0)) >>> 0, 38);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, name);
    offset += 30 + name.length + body.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(all.length, 8);
  end.writeUInt16LE(all.length, 10);
  end.writeUInt32LE(cd.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, cd, end]);
}

// Zip a folder. `pick(rel)` returns false to leave a file out.
function zipDir(dir, prefix = '', pick = () => true) {
  return makeZip(
    listFiles(dir)
      .map((f) => posix(relative(dir, f)))
      .filter(pick)
      .map((rel) => ({ name: prefix + rel, data: readFileSync(join(dir, rel)) })),
  );
}

// ---------------------------------------------------------------- tokens

function walkTokens(node, path = [], inherited) {
  const out = [];
  const type = node.$type ?? inherited;
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') || !v || typeof v !== 'object') continue;
    if ('$value' in v) out.push({ path: [...path, k], value: v.$value, type: v.$type ?? type, description: v.$description ?? '' });
    else out.push(...walkTokens(v, [...path, k], type));
  }
  return out;
}

const fontStack = (list) => list.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');

export function tokenModel(tokens) {
  const flat = walkTokens(tokens);
  const byPath = new Map(flat.map((t) => [t.path.join('.'), t]));
  const ref = (v) => (typeof v === 'string' && /^\{.+\}$/.test(v) ? byPath.get(v.slice(1, -1))?.value : v);
  const colours = { dark: [], light: [] };
  for (const t of flat.filter((t) => t.path[0] === 'color')) {
    const rest = t.path.slice(1);
    const theme = rest[0] === 'light' ? 'light' : 'dark';
    const name = rest.filter((p) => p !== 'dark' && p !== 'light').join('-');
    colours[theme].push({ name, path: rest.join('.'), value: t.value.toUpperCase(), description: t.description });
  }
  const fonts = flat.filter((t) => t.path[0] === 'font' && t.path[1] === 'family').map((t) => ({ name: t.path[2], stack: t.value, description: t.description }));
  const weights = flat.filter((t) => t.path[0] === 'font' && t.path[1] === 'weight').map((t) => ({ name: t.path[2], value: t.value }));
  const type = flat
    .filter((t) => t.path[0] === 'typography')
    .map((t) => {
      const v = t.value;
      const family = ref(v.fontFamily);
      const famName = fonts.find((f) => JSON.stringify(f.stack) === JSON.stringify(family))?.name ?? 'sans';
      return { name: t.path[1], family: famName, weight: v.fontWeight, size: v.fontSize, lineHeight: v.lineHeight, tracking: v.letterSpacing };
    });
  const pick = (root) => flat.filter((t) => t.path[0] === root).map((t) => ({ name: t.path[1], value: t.value, description: t.description }));
  const durations = flat.filter((t) => t.path[0] === 'motion' && t.path[1] === 'duration').map((t) => ({ name: t.path[2], value: t.value }));
  const eases = flat.filter((t) => t.path[0] === 'motion' && t.path[1] === 'ease').map((t) => ({ name: t.path[2], value: `cubic-bezier(${t.value.join(', ')})` }));
  return { colours, fonts, weights, type, space: pick('space'), radius: pick('radius'), size: pick('size'), durations, eases };
}

const themedNames = (m) => new Set(m.colours.light.map((c) => c.name));
const rgbChannels = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(' ');
const tracking = (t) => (String(t) === '0' ? '0' : t);
const spaceVar = (name) => (name === 'grid' ? '--strike-grid' : `--strike-space-${name}`);

