// The logo table in assets/README.md: | `file` | What it is | Use it for |
function assetsLogoTable(readmePath) {
  const map = new Map();
  if (!existsSync(readmePath)) return map;
  for (const line of read(readmePath).split('\n')) {
    const m = line.match(/^\|\s*`(strike-[\w-]+\.(?:svg|png))`\s*\|([^|]*)\|([^|]*)\|/);
    if (!m) continue;
    let use = m[3].trim().replace(/\.$/, '');
    const prev = [...map.values()].at(-1);
    // "The same, on dark grounds" refers to the row above.
    if (prev && /^(the same|as above)\b/i.test(use)) use = prev.use + use.replace(/^(the same|as above)\s*,?/i, ',');
    map.set(m[1], { what: m[2].trim(), use });
  }
  return map;
}

// dark | light | mint | photo: the first one the "use" text names, else from the file name.
function groundOf(name, use) {
  const hits = [['dark', /\bdark\b/i], ['light', /\blight\b/i], ['mint', /\bmint\b/i], ['photo', /\bphotos?\b/i]]
    .map(([k, re]) => [k, use.search(re)])
    .filter(([, i]) => i >= 0)
    .sort((a, b) => a[1] - b[1]);
  if (hits.length) return hits[0][0];
  return /black/.test(name) ? 'light' : 'dark';
}

function logoTable(logoRule) {
  const map = new Map();
  for (const line of logoRule.split('\n')) {
    if (!line.startsWith('|') || /^\|\s*-/.test(line)) continue;
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length < 3) continue;
    for (const f of cells[2].matchAll(/strike-[\w-]+\.(?:svg|png)/g)) if (!map.has(f[0])) map.set(f[0], { ground: cells[0], use: cells[1] });
  }
  return map;
}

const groundKey = (t) => (/photo/i.test(t) ? 'photo' : /mint|bright/i.test(t) ? 'mint' : /light/i.test(t) ? 'light' : /dark/i.test(t) ? 'dark' : 'any');

function logoInfo(name, table) {
  const n = name.replace(/\.(svg|png)$/, '').replace(/^strike-/, '');
  const [kind, ...rest] = n.split('-');
  const nice = { lockup: 'Lockup', mark: 'Mark', wordmark: 'Wordmark', og: 'Link preview' }[kind] ?? kind;
  const label = rest.length ? `${nice}, ${rest.join(' ').replace(/\b3d\b/i, '3D')}` : nice;
  const row = table.get(name);
  // The table's Ground column says when to use a file; its Use column names the version.
  if (row) return { label, use: /\d\s*×\s*\d/.test(row.use) ? `${row.ground}, ${row.use}` : row.ground, ground: groundKey(row.ground) };
  if (kind === 'og') return { label, use: 'Link previews, 1200 × 630', ground: 'any' };
  if (kind === 'wordmark') return { label, use: 'Only where the mark already appears nearby', ground: /white/.test(n) ? 'dark' : 'light' };
  if (/tile/.test(n)) return { label, use: 'Avatars and app icons', ground: 'any' };
  if (/disc/.test(n)) return { label, use: 'Round avatars and favicons', ground: 'any' };
  if (/white/.test(n)) return { label, use: 'Photos; one-color white', ground: 'photo' };
  if (/black|on-light/.test(n)) return { label, use: 'Light grounds', ground: 'light' };
  return { label, use: 'Dark grounds, the default', ground: 'dark' };
}

function fontFaces(fontsDir) {
  const css = join(fontsDir, 'fonts.css');
  const faces = new Map();
  if (!existsSync(css)) return faces;
  for (const block of read(css).matchAll(/@font-face\s*{([^}]*)}/g)) {
    const fam = block[1].match(/font-family\s*:\s*["']?([^"';]+)["']?/i)?.[1]?.trim();
    if (!fam) continue;
    const files = [...block[1].matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/g)].map((u) => u[1].replace(/^\.\//, '')).filter((u) => !/^(data:|https?:)/.test(u));
    faces.set(fam, [...(faces.get(fam) ?? []), ...files]);
  }
  return faces;
}

