    if (name === 'SKILL.md') return 'The Claude skill: core rules and the list of its files';
    if (name === 'AGENTS.md') return 'Core rules for AGENTS.md tools, with the list of files';
    if (name === 'copilot-instructions.md') return 'Core rules for GitHub Copilot, with the list of files';
    if (name === 'strike-design.mdc') return 'Cursor rule that always applies: the core rules';
    if (name === 'instructions.md' || name === 'gem-instructions.md') return 'Core rules to paste as instructions';
    if (name === 'space-instructions.md') return "Short rules to paste as the Space's instructions";
    if (name === 'guidelines.md') return 'Guidelines.md for Figma Make: core rules and token values';
    if (name === 'STRIKE-DESIGN.md') return 'Every rule, the facts you may use and the token values, in one file';
    if (ruleBy.has(stem) && /\.(md|mdc)$/.test(name)) return ruleBy.get(stem).info;
    if (name === 'tokens.css') return 'CSS variables, dark by default and light under [data-theme="light"], with type classes';
    if (name === 'tokens.json') return 'Design tokens in W3C Design Tokens format';
    if (name === 'tailwind.preset.cjs') return 'Tailwind v3 preset';
    if (name === 'theme.css') return 'Tailwind v4 theme';
    if (name === 'fonts.css') return '@font-face rules for the brand fonts';
    if (name === 'check.mjs') return 'Brand checker: node check.mjs <files>';
    if (name === 'lockup.mjs') return 'Sub-brand lockup generator';
    if (name === 'strike-logos.zip') return 'The logo files, SVG and PNG';
    if (name === 'strike-design-kit.zip') return 'STRIKE-DESIGN.md with the tokens, logo files and fonts';
    if (name.endsWith('.zip')) return `Everything for ${TARGET_INFO[top]?.name ?? top}, zipped`;
    if (/^strike-.*\.(svg|png)$/.test(name)) {
      const i = logoInfo(name.replace(/\.png$/, '.svg'), table);
      return `Logo: ${i.label}${name.endsWith('.png') && name !== 'strike-og.png' ? ' (PNG render)' : ''}. ${i.use}`;
    }
    if (/\.(woff2?|ttf|otf)$/.test(name)) return `Font file: ${name.replace(/\.(woff2?|ttf|otf)$/, '').replace(/[-_]/g, ' ')}`;
